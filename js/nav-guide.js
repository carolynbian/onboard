  function closestFeature(target) {
    var el = target;
    if (el && el.nodeType === 3) el = el.parentElement;
    return el && el.closest ? el.closest('[data-ng-feature]') : null;
  }

  function updateFrameNotice() {
    var notice = document.getElementById('ng-frame-notice');
    if (!notice) return;
    if (state.frameNotice) {
      notice.textContent = state.frameNotice;
      notice.hidden = false;
    } else {
      notice.textContent = '';
      notice.hidden = true;
    }
  }

  function inspectFrameAccess(doc) {
    if (!state.frameUrl || state.frameUrl.indexOf('about:blank') !== -1) {
      state.frameNotice = '';
      updateFrameNotice();
      return;
    }
    if (!doc) {
      state.frameNotice = '无法读取左侧页面状态，可能是浏览器限制本地 iframe。若页面空白，请点“新窗口打开”继续。';
      updateFrameNotice();
      return;
    }
    var text = '';
    try { text = String(doc.body ? doc.body.textContent : ''); } catch (error) { text = ''; }
    if (text.indexOf('当前账号无权进入') !== -1) {
      state.frameNotice = '当前账号无权访问这个后台页面。左侧是真实的拒绝页，不是白屏；请切换到有权限的路线/账号，或用“新窗口打开”查看完整提示。';
    } else if (doc.getElementById('login-account')) {
      state.frameNotice = '左侧页面需要登录。请先登录当前站点，或使用“新窗口打开”；学习模式不会替你在页面里登录或提交。';
    } else {
      state.frameNotice = '';
    }
    updateFrameNotice();
  }

  function scanFrameFeatures() {
    if (!overlay) return;
    var doc = getFrameDocument();
    inspectFrameAccess(doc);
    if (!doc || !doc.documentElement) return;

    var style = doc.getElementById('ng-feature-style');
    if (!style) {
      style = doc.createElement('style');
      style.id = 'ng-feature-style';
      style.textContent = [
        '[data-ng-feature]{outline:1px dashed rgba(47,111,208,.42);outline-offset:2px;border-radius:3px;transition:outline-color .15s,box-shadow .15s;}',
        '[data-ng-feature]:hover{outline:2px solid #17459a !important;box-shadow:0 0 0 3px rgba(47,111,208,.16);}',
        'html.ng-teach,html.ng-teach body,html.ng-teach body *{cursor:help !important;}',
        'html.ng-operate,html.ng-operate body,html.ng-operate body *{cursor:default !important;}',
        'html.ng-operate [data-ng-feature]{outline:none !important;box-shadow:none !important;}'
      ].join('\n');
      (doc.head || doc.documentElement).appendChild(style);
    }

    FEATURES.forEach(function (feature) {
      [].concat(feature.selector).forEach(function (selector) {
        var nodes = [];
        try { nodes = doc.querySelectorAll(selector); } catch (error) { nodes = []; }
        Array.prototype.forEach.call(nodes, function (node) {
          if (!node.getAttribute('data-ng-feature')) {
            node.setAttribute('data-ng-feature', feature.id);
          }
        });
      });
    });

    if (!doc.__ngGuideClickBound) {
      doc.addEventListener('click', function (event) {
        if (!overlay) return;
        var featureEl = closestFeature(event.target);
        if (state.mode === 'teach') {
          event.preventDefault();
          event.stopPropagation();
          if (event.stopImmediatePropagation) event.stopImmediatePropagation();
          if (featureEl) selectFeature(featureEl);
          return;
        }
        if (featureEl) recordOperation(featureEl);
      }, true);
      doc.__ngGuideClickBound = true;
    }

    applyFrameMode();
  }

  function applyFrameMode() {
    var doc = getFrameDocument();
    if (!doc || !doc.documentElement) return;
    doc.documentElement.classList.toggle('ng-teach', state.mode === 'teach');
    doc.documentElement.classList.toggle('ng-operate', state.mode === 'operate');
    if (!doc.getElementById('ng-feature-style')) scanFrameFeatures();
  }

  function selectFeature(featureEl) {
    var feature = featureById(featureEl.getAttribute('data-ng-feature'));
    if (!feature) return;
    clearRealTrace();
    state.featureId = feature.id;
    state.featureTarget = String(featureEl.textContent || feature.name).replace(/\s+/g, ' ').trim().slice(0, 60);
    state.operation = null;
    pause();
    renderAll();
  }

