  function esc(value) {
    return String(value == null ? '' : value)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }

  function currentRoute() { return ROUTES[state.route]; }
  function currentStep() { return currentRoute().steps[state.step]; }
  function pageByKey(key) { return currentRoute().pages.filter(function (p) { return p.key === key; })[0] || currentRoute().pages[0]; }

  function pageUrl(pageKey) {
    var page = pageByKey(pageKey);
    var base = page.base || currentRoute().base;
    return new URL(base + page.hash, rootUrl).href;
  }

  function detectRoute() {
    var path = String(window.location.pathname || '').replace(/\\/g, '/');
    if (/\/hr\//.test(path)) return 'hr';
    if (/\/ops\//.test(path)) return 'ops';
    try {
      if (window.OnboardStore && window.OnboardStore.currentUser) {
        var user = window.OnboardStore.currentUser();
        if (user && window.OnboardRoles) {
          var role = window.OnboardRoles.normalizeRole(user.role);
          if (role === 'hr_admin') return 'hr';
          if (role === 'ops_admin') return 'ops';
        }
      }
    } catch (error) { /* 忽略 */ }
    return 'employee';
  }

