  function pause() {
    state.playing = false;
    if (state.timer) {
      window.clearInterval(state.timer);
      state.timer = null;
    }
    var status = document.getElementById('ng-play-state');
    if (status) status.textContent = '';
  }

  function clearRealTrace() {
    if (state.traceTimer) { window.clearInterval(state.traceTimer); state.traceTimer = null; }
    if (state.replayTimer) { window.clearInterval(state.replayTimer); state.replayTimer = null; }
    state.realTrace = null;
    state.branch = null;
    state.agent = null;
  }

  function setStep(index, shouldPause) {
    var route = currentRoute();
    state.step = Math.max(0, Math.min(route.steps.length - 1, index));
    var step = currentStep();
    state.pageKey = step.page;
    state.featureId = '';
    state.featureTarget = '';
    state.operation = null;
    clearRealTrace();
    if (shouldPause) pause();
    renderAll();
    loadFrame();
  }

  function setRoute(routeKey) {
    state.route = routeKey;
    state.step = 0;
    state.pageKey = ROUTES[routeKey].steps[0].page;
    state.termName = '';
    state.showAllTerms = false;
    state.featureId = '';
    state.featureTarget = '';
    state.operation = null;
    clearRealTrace();
    pause();
    buildStepOptions();
    buildPageOptions();
    renderAll();
    loadFrame();
  }

  function loadFrame() {
    if (!overlay) return;
    var iframe = document.getElementById('ng-frame');
    var openLink = document.getElementById('ng-new-window');
    if (!iframe) return;
    var url = pageUrl(state.pageKey);
    if (state.frameUrl !== url) {
      state.frameUrl = url;
      state.frameNotice = '';
      updateFrameNotice();
      iframe.src = url;
      window.setTimeout(scanFrameFeatures, 450);
    }
    if (openLink) openLink.href = url;
  }

  function buildStepOptions() {
    var select = document.getElementById('ng-step');
    if (!select) return;
    select.innerHTML = currentRoute().steps.map(function (step, index) {
      return '<option value="' + index + '">' + String(index + 1).padStart(2, '0') + ' · ' + esc(step.label) + '</option>';
    }).join('');
    select.value = String(state.step);
  }

  function buildPageOptions() {
    var select = document.getElementById('ng-page');
    if (!select) return;
    select.innerHTML = currentRoute().pages.map(function (page) {
      return '<option value="' + esc(page.key) + '">' + esc(page.label) + '</option>';
    }).join('');
    select.value = state.pageKey || currentStep().page;
  }

  function featureById(id) {
    return FEATURES.filter(function (feature) { return feature.id === id; })[0] || null;
  }

  function currentFocus() {
    return featureById(state.featureId) || currentStep();
  }

  function renderLayerPanel(focus) {
    var active = {};
    focus.layers.forEach(function (item) { active[item.layer] = item; });
    var layerHtml = LAYERS.map(function (layer, index) {
      var call = active[index];
      return '<div class="ng-layer' + (call ? ' is-active' : '') + '">' +
        '<div class="ng-layer-name">' + esc(layer.name) + (call ? '<span class="ng-order">' + call.order + '</span>' : '') + '</div>' +
        '<p>' + esc(layer.desc) + '</p>' +
        (call ? '<p class="ng-layer-note">' + esc(call.note) + '</p>' : '') +
        '</div>';
    }).join('');
    var orderHtml = focus.order.map(function (line, index) {
      return '<li><span>' + (index + 1) + '</span>' + esc(line) + '</li>';
    }).join('');
    var isFeature = !!featureById(state.featureId);
    return '<div class="ng-panel-head"><strong>分层架构与调用逻辑</strong><span>' + (isFeature ? '当前功能' : '当前步骤') + '</span></div>' +
      '<div class="ng-layers">' + layerHtml + '</div>' +
      '<p class="ng-note">这是设计调用链，不是实时执行记录。高亮层按' + (isFeature ? '功能' : '步骤') + '讲解的假设顺序点亮，不会读取真实日志。</p>' +
      '<div class="ng-call-order"><h4>' + (isFeature ? '本功能调用顺序' : '本步调用顺序') + '</h4><ol>' + orderHtml + '</ol></div>';
  }

